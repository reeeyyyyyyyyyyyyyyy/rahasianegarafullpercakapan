// Modern Icon Wrapper Component
export const Icon = ({ 
  size = 2.5, 
  color = 'currentColor',
  strokeWidth = 2,
  className = '',
  children,
  ...props 
}) => {
  const style = {
    width: vmin(size),
    height: vmin(size),
    minWidth: vmin(size),
    minHeight: vmin(size),
  };

  return (
    <div 
      style={style} 
      className={`inline-flex items-center justify-center flex-shrink-0 ${className}`}
      {...props}
    >
      <svg 
        width="100%" 
        height="100%" 
        viewBox="0 0 24 24" 
        fill="none" 
        stroke={color}
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
      >
        {children}
      </svg>
    </div>
  );
};

